package com.fooddelivery.aimcpclient.service;

import java.time.Clock;
import java.util.List;
import java.util.UUID;
import java.util.regex.Pattern;

import com.fooddelivery.aimcpclient.client.AgentServerClient;
import com.fooddelivery.aimcpclient.dto.response.ActionConfirmResponse;
import com.fooddelivery.aimcpclient.dto.response.StoredMessage;
import com.fooddelivery.aimcpclient.exception.InvalidRequestException;
import com.fooddelivery.aimcpclient.identity.CallerIdentity;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import tools.jackson.databind.json.JsonMapper;

/**
 * The Confirm and Cancel buttons of every prepared change (an order, a cancellation, an order step, a delivery
 * step...). The decision belongs to the user; this class only forwards it with the VERIFIED identity (the server
 * checks that the change belongs to that user and role) and keeps the stored conversation consistent.
 */
@Slf4j
@Service
@RequiredArgsConstructor
public class ActionService {

    /** An order was placed by this press. */
    static final String CREATED = "CREATED";
    /** Another change was made by this press. */
    static final String DONE = "DONE";
    /** Action ids are generated by the server; anything else never reaches it (it becomes part of a URL path). */
    private static final Pattern VALID_ACTION_ID = Pattern.compile("[A-Za-z0-9_-]{1,64}");

    private final AgentServerClient agentServer;
    private final ConversationStore store;
    private final JsonMapper jsonMapper;
    private final Clock clock;

    /**
     * Makes the change. Pressing the button twice returns the server's answer again (it is idempotent);
     * the chat gets only one "done" message.
     */
    public ActionConfirmResponse confirm(CallerIdentity caller, String actionId) {
        requireValid(actionId);
        ActionConfirmResponse result = agentServer.confirm(caller, actionId);
        // The button must disappear from a restored history, also when this was the second press
        store.clearPendingAction(caller.userId(), actionId).ifPresent(conversationId -> {
            if (CREATED.equals(result.status()) || DONE.equals(result.status())) {
                store.append(caller.userId(), conversationId, List.of(confirmationMessage(result)));
            }
        });
        log.info("action confirmed id={} status={}", actionId, result.status());
        return result;
    }

    public void cancel(CallerIdentity caller, String actionId) {
        requireValid(actionId);
        agentServer.cancel(caller, actionId);
        store.clearPendingAction(caller.userId(), actionId);
        log.info("action cancelled id={}", actionId);
    }

    private StoredMessage confirmationMessage(ActionConfirmResponse result) {
        var links = result.link() == null ? jsonMapper.createArrayNode() : jsonMapper.valueToTree(List.of(result.link()));
        String text = result.message() != null ? result.message()
                : CREATED.equals(result.status()) ? "Your order has been placed." : "Done.";
        return new StoredMessage(UUID.randomUUID().toString(), ChatService.ROLE_ASSISTANT, text,
                jsonMapper.createArrayNode(), links, null, clock.instant());
    }

    private static void requireValid(String actionId) {
        if (actionId == null || !VALID_ACTION_ID.matcher(actionId).matches()) {
            throw new InvalidRequestException("Invalid action id.");
        }
    }
}
